function norm(s: string) {
  return s.trim().toLowerCase().replace(/\s+/g, "").replace(/[／/]/g, "/");
}

export function lookupTerm(query: string): TermDef | null {
  const q = norm(query);
  if (!q) return null;
  for (const row of TERMS) {
    const names = [row.term, ...row.aliases].map(norm);
    if (names.some((n) => n === q || n.includes(q) || q.includes(n))) return row;
  }
  return null;
}
